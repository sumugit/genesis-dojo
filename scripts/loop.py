"""Automatic loop: Japanese instruction -> LLM writes reward -> train -> record -> VLM evaluates -> repeat.

Usage (from the repo root):
    python scripts/loop.py --exp demo_sit --instruction "お座りして" --success-spec configs/tasks/sit.success.yaml --max-loops 3
The success spec is frozen and human-approved (`approved: true`); the loop refuses to run otherwise and aborts if the file
changes while it runs. A loop counts as a success only when the numeric check passes AND the VLM judge agrees.
Each loop i produces exp_name <exp>_L<i>:
    pai_loop/rewards/generated/<exp>_L<i>.py, configs/<exp>_L<i>.yaml, runs/<exp>_L<i>/, videos/<exp>_L<i>_<ckpt>.mp4
and appends one JSON line to logs/loops/<exp>.jsonl. Also writes runs/<exp>_L<i>/success_<ckpt>.json.
"""

import argparse
import datetime
import hashlib
import json
import os
import re
import subprocess
import sys
import time

import yaml

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from pai_loop import events, prompts, success  # noqa: E402
from pai_loop.llm import LLMError, LLMQuotaError, make_llm  # noqa: E402
from pai_loop.reward_check import load_and_check, parse_reply  # noqa: E402

parser = argparse.ArgumentParser()
parser.add_argument("--exp", required=True, help="e.g. demo_sit")
parser.add_argument("--instruction", required=True)
parser.add_argument("--success-spec", required=True, help="frozen, human-approved criteria (configs/tasks/*.success.yaml)")
parser.add_argument("--base-config", default="configs/base.yaml")
parser.add_argument("--max-loops", type=int, default=3)
parser.add_argument("--max-iterations", type=int, help="override base config")
parser.add_argument("--time-budget-s", type=int, default=3600, help="no new loop starts after this")
parser.add_argument("--train-timeout-s", type=int, default=1200)
parser.add_argument("--record-timeout-s", type=int, default=900)
parser.add_argument("--gen-retries", type=int, default=2, help="extra LLM calls when the reward fails the check")
parser.add_argument("--success-score", type=int, default=8)
parser.add_argument("--hint", help="human design advice for the reward writer (default: configs/tasks/<task>.hint.md if it exists)")
parser.add_argument("--prev-exp", help="an earlier experiment: its best loop's reward code and AI findings go into the first loop's prompt (weights are not reused)")
parser.add_argument("--llm", default="claude-cli")
parser.add_argument("--model", help="model passed to the LLM backend (default: backend default)")
args = parser.parse_args()

try:
    spec, spec_text, spec_sha = success.load_spec(args.success_spec)
except success.SpecError as e:
    sys.exit(f"success spec error: {e}")

hint_path = args.hint or os.path.join("configs", "tasks", f"{spec['task']}.hint.md")
hint_text = open(hint_path, encoding="utf-8").read() if os.path.exists(hint_path) else None

PY = sys.executable
with open(args.base_config) as f:
    base_cfg = yaml.safe_load(f)
if args.max_iterations is not None:
    base_cfg["max_iterations"] = args.max_iterations
llm = make_llm(args.llm, model=args.model)
os.makedirs("pai_loop/rewards/generated", exist_ok=True)
os.makedirs("logs/loops", exist_ok=True)
loop_log = f"logs/loops/{args.exp}.jsonl"
llm_calls = []


def ask(kind, text, images=(), system=None):
    reply = llm.ask(text, images=images, system=system)
    llm_calls.append({"kind": kind, "seconds": reply.seconds, "cost_usd": reply.cost_usd})
    print(f"[llm] {kind}: {reply.seconds}s cost={reply.cost_usd}", flush=True)
    return reply.text


def generate_reward(exp_name, history):
    request = prompts.reward_request(args.instruction, base_cfg, history, success_spec_text=spec_text, hint_text=hint_text,
                                     prior_text=prior_text)
    path = f"pai_loop/rewards/generated/{exp_name}.py"
    error = None
    for attempt in range(1, 2 + args.gen_retries):
        text = request if error is None else f"{request}\n\n# 直前の出力のエラー\n{error}\n修正したモジュール全体を出力してください。"
        reply = ask("reward", text, system=prompts.REWARD_SYSTEM)
        events.emit(args.exp, "check", "start", loop=i, attempt=attempt)
        try:
            summary, code = parse_reply(reply)
            with open(path, "w") as f:
                f.write(f'"""Generated by LLM for: {args.instruction} ({exp_name})."""\n\n' + code)
            mod = load_and_check(path)
            events.emit(args.exp, "check", "end", loop=i, attempt=attempt, ok=True)
            return summary, code, mod.PARAMS
        except Exception as e:  # any import/shape/NaN error goes back to the LLM
            error = f"{type(e).__name__}: {e}"
            events.emit(args.exp, "check", "error", loop=i, attempt=attempt, message=error[:300])
            print(f"[check] {error}", flush=True)
    raise RuntimeError(f"reward did not pass the check: {error}")


def run(cmd, log_path, timeout):
    with open(log_path, "w") as f:
        try:
            proc = subprocess.run(cmd, stdout=f, stderr=subprocess.STDOUT, timeout=timeout)
        except subprocess.TimeoutExpired:
            return f"timed out after {timeout}s"
    if proc.returncode != 0:
        with open(log_path) as f:
            return f"exit {proc.returncode}: " + f.read()[-1500:]
    return None


def train_terms(log_path):
    """Values of the last iteration printed by rsl_rl ('Mean episode rew_x: v', 'Mean reward: v', ...)."""
    with open(log_path) as f:
        text = f.read()
    last = text[text.rfind("Learning iteration"):]
    return {k: float(v) for k, v in re.findall(r"Mean (?:episode )?([\w ]+?): (-?[\d.]+)", last)}


def parse_eval(text):
    m = re.search(r"\{.*\}", text, re.S)
    if not m:
        raise ValueError("JSON not found in evaluation")
    return json.loads(m.group(0))


prior_text = None
if args.prev_exp:
    from pai_loop import prior as prior_mod
    best = prior_mod.pick_prior(prior_mod.load_entries(".", args.prev_exp))
    if best is None:
        sys.exit(f"--prev-exp {args.prev_exp}: no loop record with reward code in logs/loops/{args.prev_exp}.jsonl")
    prior_text = prior_mod.prior_section(best, args.prev_exp)
history = []
disagreements = []
events.emit(args.exp, "instruction", "end", instruction=args.instruction, task=spec["task"], spec_sha256=spec_sha,
            max_loops=args.max_loops, window_s=spec["window_s"], hint=hint_path if hint_text else None, prev_exp=args.prev_exp,
            criteria=[{"metric": c["metric"], "rule": success.describe_rule(c), "min_fraction": c.get("min_fraction"),
                       "comment": c.get("comment", "")} for c in spec["criteria"]])
t_start = time.perf_counter()
stop_reason = "max_loops"
for i in range(1, args.max_loops + 1):
    if time.perf_counter() - t_start > args.time_budget_s:
        stop_reason = "time_budget"
        break
    with open(args.success_spec, encoding="utf-8") as f:
        if hashlib.sha256(f.read().encode("utf-8")).hexdigest() != spec_sha:
            sys.exit(f"{args.success_spec} changed while the loop was running. The success spec is frozen; aborting.")
    exp_name = f"{args.exp}_L{i}"
    entry = {"exp_name": exp_name, "loop": i, "instruction": args.instruction,
             "started": datetime.datetime.now().isoformat(timespec="seconds"),
             "success_spec": {"path": args.success_spec, "sha256": spec_sha},
             "hint": hint_path if hint_text else None, "prev_exp": args.prev_exp}
    n_calls = len(llm_calls)
    t_loop = time.perf_counter()
    print(f"=== {exp_name} ===", flush=True)
    events.emit(args.exp, "reward", "start", loop=i, exp_name=exp_name)
    try:
        summary, code, params = generate_reward(exp_name, history)
        entry.update(reward_summary=summary, reward_code=code)
        events.emit(args.exp, "reward", "end", loop=i, summary=summary, code=code)
        cfg = dict(base_cfg, exp_name=exp_name, instruction=args.instruction,
                   reward={"module": f"pai_loop.rewards.generated.{exp_name}", "params": params})
        cfg_path = f"configs/{exp_name}.yaml"
        with open(cfg_path, "w") as f:
            yaml.safe_dump(cfg, f, sort_keys=False, allow_unicode=True, default_flow_style=None, width=120)

        events.emit(args.exp, "train", "start", loop=i, iterations=base_cfg["max_iterations"])
        err = run([PY, "scripts/train.py", cfg_path], f"logs/{exp_name}_train.log", args.train_timeout_s)
        if err:
            raise RuntimeError(f"training failed: {err}")
        with open(f"runs/{exp_name}/summary.json") as f:
            entry["train"] = json.load(f)
        events.emit(args.exp, "train", "end", loop=i, seconds=entry["train"].get("train_seconds"),
                    final_mean_reward=entry["train"].get("final_mean_reward"), checkpoint=entry["train"]["last_checkpoint"])
        entry["train_terms"] = train_terms(f"logs/{exp_name}_train.log")

        events.emit(args.exp, "record", "start", loop=i)
        err = run([PY, "scripts/record.py", exp_name], f"logs/{exp_name}_record.log", args.record_timeout_s)
        if err:
            raise RuntimeError(f"recording failed: {err}")
        with open(f"runs/{exp_name}/metrics_{entry['train']['last_checkpoint']}.json") as f:
            metrics = json.load(f)
        entry["metrics"] = {k: v for k, v in metrics.items() if k != "series_0p1s"}
        events.emit(args.exp, "record", "end", loop=i, video=os.path.basename(metrics["video"]),
                    seconds=metrics.get("record_wall_seconds"))

        check = success.evaluate(metrics, spec)
        entry["success_check"] = check
        with open(f"runs/{exp_name}/success_{entry['train']['last_checkpoint']}.json", "w") as f:
            json.dump(check, f, indent=1, ensure_ascii=False)
        print(success.format_result(check), flush=True)
        events.emit(args.exp, "numeric", "end", loop=i, result=check)

        # Blind scoring: the judge sees the instruction, frames and metrics, not the reward code or the numeric verdict.
        events.emit(args.exp, "vlm", "start", loop=i)
        eval_text = ask("evaluate", prompts.eval_request(args.instruction, metrics),
                        images=[fr["path"] for fr in metrics["frames"]], system=prompts.EVAL_SYSTEM)
        entry["evaluation"] = parse_eval(eval_text)
        events.emit(args.exp, "vlm", "end", loop=i, evaluation=entry["evaluation"])
    except LLMQuotaError as e:
        entry["error"] = f"LLM quota: {e}"
        stop_reason = "llm_quota"
    except (LLMError, RuntimeError, ValueError, json.JSONDecodeError) as e:
        entry["error"] = f"{type(e).__name__}: {e}"
    if entry.get("error"):
        events.emit(args.exp, "error", "error", loop=i, message=str(entry["error"])[:400])
    ev = entry.get("evaluation", {})
    check = entry.get("success_check")
    if check is not None and ev:
        try:
            score = float(ev.get("score", 0))
        except (TypeError, ValueError):
            score = 0.0
        num_ok = bool(check["passed"])
        vlm_ok = bool(ev.get("success")) and score >= args.success_score
        disagreement = ("numeric_pass_vlm_fail" if num_ok and not vlm_ok
                        else "numeric_fail_vlm_pass" if vlm_ok and not num_ok else None)
        entry["decision"] = {"numeric_pass": num_ok, "vlm_pass": vlm_ok, "success": num_ok and vlm_ok,
                             "disagreement": disagreement}
        if disagreement:
            disagreements.append({"exp_name": exp_name, "kind": disagreement})
            print(f"[disagreement] {exp_name}: {disagreement}（数値判定とVLMの判定が食い違った。成功条件の抜けや評価の甘さの疑い）", flush=True)
        events.emit(args.exp, "decision", "end", loop=i, decision=entry["decision"])
    entry["llm_calls"] = llm_calls[n_calls:]
    entry["loop_seconds"] = round(time.perf_counter() - t_loop, 1)
    with open(loop_log, "a") as f:
        f.write(json.dumps(entry, ensure_ascii=False) + "\n")
    decision = entry.get("decision", {})
    print(f"[loop {i}] numeric={check['passed'] if check else None} vlm_score={ev.get('score')} "
          f"vlm_success={ev.get('success')} decision={decision} error={entry.get('error')}", flush=True)
    history.append(entry)
    if stop_reason == "llm_quota":
        break
    if decision.get("success"):
        stop_reason = "success"
        break

total_cost = sum(c["cost_usd"] or 0 for c in llm_calls)
events.emit(args.exp, "run", "end", stop_reason=stop_reason, loops=len(history), llm_cost_usd_equiv=round(total_cost, 3),
            total_seconds=round(time.perf_counter() - t_start, 1), disagreements=disagreements)
print(json.dumps({"stop_reason": stop_reason, "loops": len(history), "llm_calls": len(llm_calls),
                  "llm_cost_usd_equiv": round(total_cost, 3),
                  "total_seconds": round(time.perf_counter() - t_start, 1),
                  "success_spec_sha256": spec_sha, "disagreements": disagreements}, ensure_ascii=False))
